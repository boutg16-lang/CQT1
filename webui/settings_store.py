"""Persistent AI settings for the ViralCutter WebUI.

The WebUI can resolve keys from the environment, the encrypted store, or a
legacy plaintext config. New keys are never written to plaintext: encrypted
persistence requires VIRALCUTTER_CONFIG_PASSPHRASE, while existing legacy
files remain readable and can be migrated without discarding user data.

No gradio imports — pure and unit-testable.
"""
import json
import logging
import os
import re
import sys
import tempfile

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from scripts.gemini_models import DEFAULT_GEMINI_MODEL, resolve_gemini_model
from scripts.secure_config import legacy_config_path, load_api_config

logger = logging.getLogger(__name__)

# Local UI-preferences file (user-machine state, NOT tracked by git).
WEBUI_PREFS_FILE = "webui_settings.json"

# Fields the WebUI persists. Keys match api_config.json.
PERSISTED_KEYS = ("ai_backend", "ai_model", "chunk_size")

KEY_SOURCE_ENV = "env"
KEY_SOURCE_SECURE = "secure"
KEY_SOURCE_FILE = "file"
KEY_SOURCE_NONE = "none"

# Gemini keys are generated by AI Studio and always start with this prefix.
GEMINI_KEY_PREFIX = "AIza"

# placeholders that mean "no real key" in api_config.json
FAKE_KEYS = {"", "SUA_KEY_AQUI", "YOUR_KEY_HERE"}
VALID_BACKENDS = {"gemini", "g4f", "local", "manual", "openai", "auto"}
MIN_CHUNK_SIZE = 1
MAX_CHUNK_SIZE = 200000


def _atomic_write_json(path, data, *, indent=2, restrict=False):
    """Atomically persist *data* as JSON using a per-writer temp file.

    Gradio runs handlers on a thread pool and ~30 components autosave, so a
    shared ``path + ".tmp"`` lets concurrent saves interleave on the same
    inode; ``os.replace`` then publishes a file that is valid JSON with
    trailing garbage. ``mkstemp`` gives every writer its own temp file, so
    each save is an independent atomic replace.

    ``restrict`` applies owner-only permissions (0o600) where supported, for
    files that may contain plaintext credentials.
    """
    directory = os.path.dirname(os.path.abspath(path)) or "."
    os.makedirs(directory, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=directory, suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=indent)
            f.write("\n")
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
        if restrict:
            try:
                os.chmod(path, 0o600)
            except OSError:
                pass
    finally:
        if os.path.exists(tmp):
            try:
                os.remove(tmp)
            except OSError:
                pass


def _coerce_chunk(value, default):
    try:
        return max(MIN_CHUNK_SIZE, min(MAX_CHUNK_SIZE, int(value)))
    except (TypeError, ValueError, OverflowError):
        return int(default)


def _defaults():
    return {
        "selected_api": "auto",
        "gemini": {
            "api_key": "",
            "api_keys": [],
            "key_mode": "auto",
            "model": DEFAULT_GEMINI_MODEL,
            "chunk_size": 20000,
        },
        "g4f": {"model": "gpt-4o-mini", "chunk_size": 2000},
        "openai": {
            "base_url": "http://localhost:11434/v1",
            "api_key": "",
            "model": "llama3.1",
            "chunk_size": 12000,
            "embedding_model": "bge-m3",
            "embeddings": False,
        },
    }


def load_ui_settings(base_dir=None):
    """Resolve the settings the WebUI should show.

    Returns dict:
      ai_backend  — "gemini" | "g4f" | "local" | "manual"
      api_key     — resolved key ("" when none)
      key_source  — "env" | "secure" | "file" | "none"
      ai_model    — model name for the selected backend
      chunk_size  — chunk size for the selected backend
    """
    config = load_api_config(base_dir) or _defaults()
    if not isinstance(config, dict):
        config = _defaults()
    backend = config.get("selected_api") or "gemini"
    if backend not in VALID_BACKENDS:
        backend = "gemini"
    gemini = config.get("gemini") or {}
    if not isinstance(gemini, dict):
        gemini = {}

    # Resolve up to three keys in the same priority order as the CLI.
    from scripts.secure_config import get_keys as _secure_get_keys
    from scripts.secure_config import resolve_api_keys as _resolve_keys
    from scripts.secure_config import secure_config_path
    keys = []
    source = KEY_SOURCE_NONE
    env_keys = _resolve_keys(base_dir=base_dir, warn=False) if os.getenv("VIRALCUTTER_GEMINI_KEYS") or os.getenv("VIRALCUTTER_GEMINI_KEY") or os.getenv("GEMINI_API_KEY") else []
    if env_keys:
        keys, source = env_keys, KEY_SOURCE_ENV
    else:
        try:
            keys = _secure_get_keys(base_dir=base_dir)
        except Exception as exc:
            logger.warning("Could not load encrypted Gemini settings (%s).", type(exc).__name__)
            keys = []
        if keys:
            source = KEY_SOURCE_SECURE
    secure_store_exists = os.path.isfile(secure_config_path(base_dir))
    if not keys and not secure_store_exists:
        file_keys = gemini.get("api_keys") or [gemini.get("api_key", "")]
        keys = [str(item).strip() for item in file_keys if str(item or "").strip() not in FAKE_KEYS][:3]
        if keys:
            source = KEY_SOURCE_FILE
    key = keys[0] if keys else ""

    openai_cfg = config.get("openai") or {}
    if not isinstance(openai_cfg, dict):
        openai_cfg = {}
    if backend == "gemini":
        backend_cfg = gemini
    elif backend == "openai":
        backend_cfg = openai_cfg
    elif backend == "auto":
        backend_cfg = {}
    else:
        backend_cfg = config.get("g4f") or {}
    if not isinstance(backend_cfg, dict):
        backend_cfg = {}
    model = backend_cfg.get("model") or gemini.get("model") or ""
    if backend == "gemini":
        model = resolve_gemini_model(model)
    if backend == "auto":
        model = "Auto"
    if backend == "openai":
        # Local servers need no key; hosted ones read OPENAI_API_KEY.
        key = (os.getenv("OPENAI_API_KEY", "").strip()
               or os.getenv("VIRALCUTTER_OPENAI_KEY", "").strip()
               or str(openai_cfg.get("api_key") or "").strip())
        if key:
            source = KEY_SOURCE_ENV if os.getenv("OPENAI_API_KEY") or os.getenv("VIRALCUTTER_OPENAI_KEY") else KEY_SOURCE_FILE
    default_chunk = (20000 if backend == "gemini"
                     else 12000 if backend in {"openai", "auto"} else 2000)
    chunk = _coerce_chunk(backend_cfg.get("chunk_size"), default_chunk)
    if backend == "openai" and not model:
        model = str(openai_cfg.get("model") or "llama3.1")

    return {
        "ai_backend": backend,
        "api_key": key,
        "api_keys": keys,
        "key_mode": str(gemini.get("key_mode") or "auto") if str(gemini.get("key_mode") or "auto") in {"auto", "1", "2", "3"} else "auto",
        "key_source": source,
        "ai_model": model,
        "chunk_size": chunk,
        "openai_base_url": str(
            os.getenv("VIRALCUTTER_OPENAI_BASE_URL", "").strip()
            or os.getenv("OPENAI_BASE_URL", "").strip()
            or openai_cfg.get("base_url") or "http://localhost:11434/v1"),
        "embedding_model": str(openai_cfg.get("embedding_model") or "bge-m3"),
        "embeddings": bool(openai_cfg.get("embeddings")) or str(
            os.getenv("VIRALCUTTER_EMBEDDINGS", "")).strip().lower() in {
                "1", "true", "yes", "on"},
    }


def save_ui_settings(ai_backend=None, api_key=None, ai_model=None, chunk_size=None,
                     base_dir=None, api_keys=None, key_mode=None):
    """Persist settings without writing Gemini keys to the legacy plaintext file."""
    path = legacy_config_path(base_dir)
    config = _defaults()
    if os.path.exists(path):
        try:
            with open(path, "r", encoding="utf-8") as f:
                loaded = json.load(f)
            if not isinstance(loaded, dict):
                return False, "ملف الإعدادات ليس كائن JSON صالحاً؛ لم يتم تغييره."
            for section in ("gemini", "g4f"):
                if section in loaded and not isinstance(loaded[section], dict):
                    return False, "بنية ملف الإعدادات غير صالحة؛ لم يتم تغييره."
            config.update(loaded)
        except (OSError, UnicodeError, ValueError, TypeError) as exc:
            logger.warning("Could not read saved AI settings (%s); refusing to replace the file.",
                           type(exc).__name__)
            return False, "تعذّرت قراءة ملف الإعدادات؛ لم يتم تغييره."

    for section in ("gemini", "g4f", "openai"):
        if not isinstance(config.get(section), dict):
            config[section] = {}

    env_keys = []
    from scripts.secure_config import resolve_api_keys as _resolve_keys
    if any(os.getenv(name) for name in (
            "VIRALCUTTER_GEMINI_KEYS", "VIRALCUTTER_GEMINI_KEY", "GEMINI_API_KEY")):
        env_keys = _resolve_keys(base_dir=base_dir, warn=False)
    if ai_backend in VALID_BACKENDS:
        config["selected_api"] = ai_backend
    if config.get("selected_api") not in VALID_BACKENDS:
        config["selected_api"] = "gemini"
    backend = config["selected_api"]

    supplied_keys = api_keys if api_keys is not None else ([api_key] if api_key else [])
    clean_keys = []
    for value in supplied_keys or []:
        value = str(value or "").strip()
        if value and value not in FAKE_KEYS and value not in clean_keys:
            clean_keys.append(value)
        if len(clean_keys) >= 3:
            break
    # A key typed while the OpenAI-compatible backend is selected belongs to
    # that provider, not to Gemini. Only persist it when it clearly looks like
    # a Gemini key, otherwise the runner receives it through the environment
    # for the current run and nothing is written to disk.
    openai_backend = backend == "openai"
    if openai_backend:
        clean_keys = [key for key in clean_keys
                      if key.startswith(GEMINI_KEY_PREFIX)]
    if clean_keys and not env_keys:
        config["gemini"]["api_keys"] = clean_keys
        config["gemini"]["api_key"] = clean_keys[0]
    elif not isinstance(config["gemini"].get("api_keys"), list):
        legacy_key = str(config["gemini"].get("api_key") or "").strip()
        config["gemini"]["api_keys"] = [legacy_key] if legacy_key and legacy_key not in FAKE_KEYS else []

    if key_mode in {"auto", "1", "2", "3"}:
        config["gemini"]["key_mode"] = key_mode

    section = (config["gemini"] if backend == "gemini"
               else config["openai"] if backend == "openai"
               else config["g4f"] if backend == "g4f" else None)
    if ai_model and section is not None:
        if backend == "gemini":
            supported_model = resolve_gemini_model(ai_model)
            if supported_model != str(ai_model).strip():
                return False, "Gemini model is unavailable; choose one of the listed models."
            section["model"] = supported_model
        else:
            section["model"] = str(ai_model).strip()
    if chunk_size is not None and section is not None:
        default_chunk = (20000 if backend == "gemini"
                         else 12000 if backend == "openai" else 2000)
        section["chunk_size"] = _coerce_chunk(chunk_size, default_chunk)

    stored = config["gemini"].get("api_keys") or [config["gemini"].get("api_key", "")]
    if isinstance(stored, str):
        stored = [stored]
    stored_keys = [str(value or "").strip() for value in stored
                   if str(value or "").strip() not in FAKE_KEYS]
    passphrase = os.environ.get("VIRALCUTTER_CONFIG_PASSPHRASE", "").strip()
    if stored_keys and not passphrase:
        return False, (
            "لم يتم حفظ التغييرات لأن مفاتيح Gemini لا تُحفظ كنص مكشوف. "
            "اضبط VIRALCUTTER_CONFIG_PASSPHRASE للحفظ المشفّر؛ لم يتم تعديل الملف."
        )
    if stored_keys:
        try:
            from scripts.secure_config import set_keys
            set_keys(stored_keys, passphrase=passphrase, base_dir=base_dir)
        except Exception as exc:
            logger.warning("Encrypted Gemini key storage failed (%s); settings were not written.",
                           type(exc).__name__)
            return False, "تعذّر حفظ المفتاح مشفّراً؛ لم يتم حفظ الإعدادات."
        config["gemini"]["api_key"] = ""
        config["gemini"]["api_keys"] = []

    try:
        _atomic_write_json(path, config, indent=4, restrict=True)
        return True, ""
    except (OSError, TypeError, ValueError) as exc:
        logger.warning("Could not persist AI settings (%s).", type(exc).__name__)
        return False, "تعذّر حفظ الإعدادات؛ راجع سجل التطبيق للتفاصيل."

def mask_key(key, visible_head=4, visible_tail=4):
    """Mask a key for display: AIza****wxyz (short keys fully masked)."""
    key = (key or "").strip()
    if not key:
        return ""
    if len(key) <= visible_head + visible_tail + 4:
        return key[:visible_head] + "*" * 4 + key[-2:]
    return key[:visible_head] + "*" * 8 + key[-visible_tail:]


def looks_like_gemini_key(key):
    """Heuristic guard: Gemini keys are ~39 chars and start with AIza."""
    key = (key or "").strip()
    if not key:
        return False
    return key.startswith(GEMINI_KEY_PREFIX)


def _safe_api_error(message, api_key=""):
    text = str(message or "").strip()
    if api_key:
        text = text.replace(api_key, "[redacted]")
    text = re.sub(r"(?i)([?&](?:key|api_key)=)[^&\s]+", r"\1[redacted]", text)
    text = re.sub(r"(?i)(api[_ -]?key\s*[:=]\s*)[^,\s]+", r"\1[redacted]", text)
    return text[:300] or "request failed"


def _rest_test_gemini(api_key, timeout=10):
    """Fallback REST check without exposing the key in a URL or error."""
    import json as _json
    import urllib.error
    import urllib.request

    url = "https://generativelanguage.googleapis.com/v1beta/models"
    req = urllib.request.Request(
        url, headers={"User-Agent": "ViralCutter/1.0", "X-Goog-Api-Key": api_key.strip()})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            data = _json.loads(resp.read().decode("utf-8", "replace"))
            models = data.get("models", [])
            return True, "{} models".format(len(models))
    except urllib.error.HTTPError as exc:
        try:
            payload = _json.loads(exc.read(4096).decode("utf-8", "replace"))
            error = payload.get("error") or {}
            detail = _safe_api_error(error.get("message", "request rejected"), api_key)
        except (OSError, UnicodeError, ValueError, TypeError, AttributeError) as read_exc:
            logger.warning("Could not read Gemini error response (%s).", type(read_exc).__name__)
            detail = "request rejected"
        return False, "HTTP {}: {}".format(exc.code, detail)
    except Exception as exc:
        logger.warning("Gemini REST check failed (%s).", type(exc).__name__)
        return False, "Network request failed ({})".format(type(exc).__name__)


def test_gemini_connection(api_key, model_name=DEFAULT_GEMINI_MODEL, timeout=10):
    """Validate a Gemini API key without echoing it in errors."""
    key = (api_key or "").strip()
    if not key:
        return False, "Gemini API key is empty"
    try:
        import importlib
        try:
            client = importlib.import_module("google.genai").Client(api_key=key)
            resp = client.models.generate_content(
                model=model_name, contents="Reply with exactly: ok",
                config={"http_options": {"timeout": timeout * 1000}})
            return True, (getattr(resp, "text", "") or "").strip()
        except ImportError:
            try:
                genai = importlib.import_module("google.generativeai")
                genai.configure(api_key=key)
                model = genai.GenerativeModel(model_name)
                resp = model.generate_content("Reply with exactly: ok", request_options={"timeout": timeout})
                text = getattr(resp, "text", "") or ""
                return True, text.strip()
            except ImportError:
                return _rest_test_gemini(key, timeout)
    except Exception as exc:
        error = _safe_api_error(str(exc), key)
        if "API key not valid" in error or "API_KEY_INVALID" in error:
            return False, "API key not valid"
        if "quota" in error.lower() or "RESOURCE_EXHAUSTED" in error:
            return False, "quota exceeded"
        if "PERMISSION_DENIED" in error:
            return False, "permission denied"
        logger.warning("Gemini key check failed (%s).", type(exc).__name__)
        return False, "Gemini key check failed ({})".format(type(exc).__name__)


